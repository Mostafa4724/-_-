/* Translation helper */
function t(key) {
  const lang = document.documentElement.getAttribute('data-lang') || 'en';
  return (I18N[lang] && I18N[lang][key]) || (I18N.en[key]) || key;
}

/* Apply translations to all elements with data-i18n */
function applyTranslations() {
  const lang = document.documentElement.getAttribute('data-lang') || 'en';
  document.documentElement.setAttribute('dir', I18N[lang].dir);
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N[lang][key]) el.textContent = I18N[lang][key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (I18N[lang][key]) el.setAttribute('placeholder', I18N[lang][key]);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (I18N[lang][key]) el.setAttribute('title', I18N[lang][key]);
  });
  // Page title
  const pageTitleEl = document.querySelector('[data-page-title]');
  if (pageTitleEl) {
    document.title = (pageTitleEl.textContent || 'Dashboard') + ' · EduPlatform';
  }
}
